import { spawnSync } from 'node:child_process'
// Read-only, offline preflight. Does not invoke package managers or installers.
import { existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const missing = []
function check(name, available) {
  console.log(`${available ? 'OK' : 'MISSING'}: ${name}`)
  if (!available)
    missing.push(name)
}

for (const [name, path] of [
  ['pnpm project dependencies', 'node_modules/.modules.yaml'],
  ['vue-tsc', 'apps/desktop/node_modules/vue-tsc/bin/vue-tsc.js'],
  ['Vite', 'apps/desktop/node_modules/vite/bin/vite.js'],
  ['Tauri CLI', 'apps/desktop/node_modules/@tauri-apps/cli/tauri.js'],
]) {
  check(name, existsSync(join(root, path)))
}

const rustHome = process.env.RUSTUP_HOME || join(homedir(), '.rustup')
const rustBin = join(rustHome, 'toolchains/stable-x86_64-pc-windows-msvc/bin')
check('Rust stable MSVC compiler', existsSync(join(rustBin, 'rustc.exe')))
check('Cargo.lock (generated by your first cargo fetch/build)', existsSync(join(root, 'Cargo.lock')))

if (process.platform === 'win32') {
  const vswhere = join(process.env['ProgramFiles(x86)'] || 'C:/Program Files (x86)', 'Microsoft Visual Studio/Installer/vswhere.exe')
  const result = existsSync(vswhere)
    ? spawnSync(vswhere, ['-latest', '-products', '*', '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64', '-find', 'VC/Tools/MSVC/**/bin/Hostx64/x64/link.exe'], { encoding: 'utf8', windowsHide: true })
    : null
  const onPath = (process.env.PATH || '').split(';').some(directory => existsSync(join(directory, 'link.exe')))
  check('MSVC linker', onPath || (result?.status === 0 && !!result.stdout.trim()))
}

console.log('\nNo downloads or installations were performed.')
if (missing.length)
  process.exitCode = 1
